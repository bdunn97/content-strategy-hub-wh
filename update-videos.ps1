# Rebuilds videos.js from the "Competitor Ads" folder.
# Each subfolder = one brand section; every .mp4/.mov/.webm/.m4v inside = one video card.
# Usage (from this folder):  powershell -ExecutionPolicy Bypass -File .\update-videos.ps1

$root = Join-Path $PSScriptRoot 'Competitor Ads'
$exts = '.mp4', '.mov', '.webm', '.m4v'

$brands = Get-ChildItem -LiteralPath $root -Directory | Sort-Object Name | ForEach-Object {
    $files = Get-ChildItem -LiteralPath $_.FullName -File |
        Where-Object { $exts -contains $_.Extension.ToLower() } |
        Sort-Object Name | ForEach-Object { $_.Name }
    if ($files) { [pscustomobject]@{ brand = $_.Name; videos = @($files) } }
}

$json = ConvertTo-Json -InputObject @($brands) -Depth 4
$out = @"
// Auto-generated by update-videos.ps1 - re-run that script after adding videos to "Competitor Ads".
// Each brand folder becomes one carousel section on the Competitor Ads tab.
window.COMPETITOR_ADS = $json;
"@
[System.IO.File]::WriteAllText((Join-Path $PSScriptRoot 'videos.js'), $out, (New-Object System.Text.UTF8Encoding $false))
Write-Host "videos.js updated: $(@($brands).Count) brands, $((@($brands) | ForEach-Object { $_.videos.Count } | Measure-Object -Sum).Sum) videos"
